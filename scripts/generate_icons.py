#!/usr/bin/env python3
"""Generate web PNGs, the Android vector and TV banner from the favicon artwork.

Run `python3 scripts/generate_icons.py` after editing web/static/favicon.svg.
Requires ImageMagick (`magick`); PNGs render at 4x size before downsampling.
"""

from pathlib import Path
import subprocess
import tempfile
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
STATIC = ROOT / "web/static"
RES = ROOT / "android/src/main/res"
SVG_NS = "{http://www.w3.org/2000/svg}"


def main():
    source = ET.parse(STATIC / "favicon.svg").getroot()
    mark = source.find(f"{SVG_NS}path")
    background = source.find(f"{SVG_NS}rect")
    assert mark is not None and background is not None

    with tempfile.TemporaryDirectory(prefix="cloudstream-icons-") as temporary:
        for name, size, rounded in (
            ("icon-192.png", 192, True),
            ("icon-512.png", 512, True),
            ("icon-maskable-512.png", 512, False),
            ("apple-touch-icon.png", 180, False),
        ):
            # Maskable and Apple icons need full-bleed backgrounds: the OS
            # supplies their shape. Ordinary PWA icons keep rounded corners.
            background.set("rx", "24" if rounded else "0")
            svg = Path(temporary) / "icon.svg"
            ET.ElementTree(source).write(svg, encoding="unicode")
            subprocess.run(
                [
                    "magick", "-background", "none", "-density", str(size * 4 * 96 / 108),
                    str(svg), "-resize", f"{size * 4}x{size * 4}",
                    "-resize", f"{size}x{size}", "-strip",
                    f"PNG32:{STATIC / 'icons' / name}",
                ],
                check=True,
            )

        banner = Path(temporary) / "banner.svg"
        banner.write_text(f'''<svg xmlns="http://www.w3.org/2000/svg" width="320" height="180" viewBox="0 0 320 180">
  <rect width="320" height="180" fill="{background.attrib['fill']}"/>
  <g transform="translate(117 10) scale(0.8)">
    <path fill="{mark.attrib['fill']}" fill-rule="evenodd" d="{mark.attrib['d']}"/>
  </g>
  <text x="160" y="131" text-anchor="middle" font-family="DejaVu Sans" font-size="24" fill="#eceef3">Cloudstream</text>
</svg>
''')
        subprocess.run(
            [
                "magick", "-background", "none", "-density", "384",
                str(banner), "-resize", "320x180", "-strip",
                f"PNG32:{RES / 'drawable-nodpi/tv_banner.png'}",
            ],
            check=True,
        )

    # Keep the same silhouette inside Android's central 66dp safe zone.
    # The transparent play cutout also works as the themed monochrome layer.
    vector = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate_icons.py from web/static/favicon.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:pivotX="54"
        android:pivotY="54"
        android:scaleX="0.72"
        android:scaleY="0.72">
        <path
            android:fillColor="{mark.attrib['fill']}"
            android:fillType="evenOdd"
            android:pathData="{mark.attrib['d']}" />
    </group>
</vector>
'''
    (RES / "drawable/ic_launcher_foreground.xml").write_text(vector)


if __name__ == "__main__":
    main()
